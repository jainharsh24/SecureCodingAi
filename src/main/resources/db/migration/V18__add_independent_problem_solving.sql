ALTER TABLE submissions
    ADD COLUMN independent_problem_solving_score INTEGER,
    ADD COLUMN highest_hint_assistance VARCHAR(32);

CREATE TABLE hint_view_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    challenge_id BIGINT NOT NULL REFERENCES challenges(id),
    assistance_level VARCHAR(32) NOT NULL,
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_hint_view_user_challenge_level UNIQUE (user_id, challenge_id, assistance_level)
);
