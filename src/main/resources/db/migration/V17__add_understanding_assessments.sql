CREATE TABLE understanding_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    challenge_id BIGINT NOT NULL REFERENCES challenges(id),
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    root_cause_points INTEGER NOT NULL,
    mechanism_points INTEGER NOT NULL,
    prevention_points INTEGER NOT NULL,
    score INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    root_cause_feedback TEXT,
    mechanism_feedback TEXT,
    prevention_feedback TEXT,
    unavailable_reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_understanding_assessments_user_challenge ON understanding_assessments(user_id, challenge_id, id);
